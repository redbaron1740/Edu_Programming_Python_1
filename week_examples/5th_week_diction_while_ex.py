import subprocess

subprocess.run('cls', shell=True)

# 과목과 점수를 '키: 값' 형태로 저장할 딕셔너리
과목_점수 = {
    "국어": 0,
    "영어": 0,
    "수학": 0,
    "과학": 0,
    "사회": 0
}

# 1. 과목별 점수 입력 받기 (dict.keys() 활용)
for 과목 in 과목_점수.keys():
    while True:
        try:
            점수 = float(input(f"{과목} 점수를 입력하세요: "))
            if 0 <= 점수 <= 100:
                과목_점수[과목] = 점수  # 딕셔너리에 과목별 점수 저장
                break
            else:
                print("0에서 100 사이의 점수를 입력해주세요.")
        except ValueError:
            print("유효한 숫자를 입력해주세요.")

# 2. 평균 및 성적 요약 계산 (dict.values() 활용)
점수들 = 과목_점수.values()
평균 = sum(점수들) / len(점수들)

# 3. 결과 출력
print("\n==============================")
print("       📊 성적 입력 결과")
print("==============================")
for 과목, 점수 in 과목_점수.items():
    print(f"  • {과목}: {점수:.1f}점")
print("------------------------------")
print(f"  🏆 평균 점수: {평균:.2f}점")
print("==============================")